const { test } = require('node:test')
const assert = require('node:assert/strict')
const { createDownloadTracker, stripUrl } = require('../../app/lib/cdp-downloads')
const { createFakeCdp } = require('./browser-hub-fake-cdp')

test('start enables events and tolerates failure', async () => {
  const c = createFakeCdp()
  await createDownloadTracker({ client: c }).start()
  assert.deepEqual(c.calls[0], { method: 'Browser.setDownloadBehavior', params: { behavior: 'default', eventsEnabled: true }, sessionId: undefined })
  const bad = createFakeCdp({ 'Browser.setDownloadBehavior': () => { throw new Error('x') } })
  await createDownloadTracker({ client: bad }).start()
})

test('tracks begin/progress/complete with name only and stripped url', () => {
  const c = createFakeCdp()
  const t = createDownloadTracker({ client: c })
  c.emit('Browser.downloadWillBegin', { guid: 'g1', url: 'https://a.test/f.zip?token=SECRET#h', suggestedFilename: '..\\..\\evil\\f.zip' })
  c.emit('Browser.downloadProgress', { guid: 'g1', receivedBytes: 10, state: 'inProgress' })
  assert.equal(t.list().items[0].state, 'in_progress')
  c.emit('Browser.downloadProgress', { guid: 'g1', receivedBytes: 99, state: 'completed' })
  c.emit('Browser.downloadWillBegin', { guid: 'g2', url: 'https://b.test/x', suggestedFilename: 'x.bin' })
  c.emit('Browser.downloadProgress', { guid: 'g2', state: 'canceled' })
  const { items } = t.list()
  assert.equal(items[1].fileName, 'f.zip')
  assert.equal(items[1].url, 'https://a.test/f.zip')
  assert.equal(items[1].state, 'completed')
  assert.equal(items[1].bytes, 99)
  assert.equal(items[0].state, 'interrupted')
  assert.ok(!JSON.stringify(items).includes('SECRET'))
})

test('list honours limit and max', () => {
  const c = createFakeCdp()
  const t = createDownloadTracker({ client: c, max: 3 })
  for (let i = 0; i < 5; i++) c.emit('Browser.downloadWillBegin', { guid: 'g' + i, url: 'https://a.test/', suggestedFilename: 'f' + i })
  assert.equal(t.list().items.length, 3)
  assert.equal(t.list({ limit: 1 }).items[0].downloadId, 'g4')
  assert.equal(stripUrl('nope'), '')
})
